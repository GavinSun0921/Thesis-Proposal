#!/usr/bin/env python3
"""Section 1.2: three independent count charts and non-uniform calendar timelines.
Native dimensions are intentional; the thesis inputs these without resizebox.
Usage: python3 .../build_literature_trend_figures.py [--tex] [--timelines-only]
"""
import hashlib,json,math,shutil,subprocess,sys
from pathlib import Path
FIGURES=Path(__file__).resolve().parent
ROOT=FIGURES.parent.parent
STATS=ROOT/'docs/literature_stats'
OUT=FIGURES/'generated/literature_trend'
WORK=ROOT/'tmp/literature-trend-build'
FONT=r'\songti\fontsize{9.2pt}{11pt}\selectfont'
SMALL=r'\songti\fontsize{8.8pt}{10.2pt}\selectfont'
HEAD=r'\heiti\fontsize{9.2pt}{11pt}\selectfont'
def esc(s):return s.replace('&',r'\&').replace('%',r'\%').replace('_',r'\_')
def ticks(maximum):
    raw=maximum/4
    mag=10**math.floor(math.log10(max(raw,1)))
    step=next(f*mag for f in (1,2,2.5,5,10) if f*mag>=raw)
    if step<1:step=1
    return [int(i*step) for i in range(math.ceil(maximum*1.13/step)+1)]
def start(comment):
    return ['% !TeX root = ../main.tex','% Generated by build_literature_trend_figures.py; '+comment,
        r'\begingroup',r'\linespread{1}\selectfont',
        r'\definecolor{litDark}{HTML}{2F5A86}',r'\definecolor{litLine}{HTML}{4E779E}',r'\definecolor{litTint}{HTML}{E4EEF7}',
        r'\begin{tikzpicture}[x=1cm,y=1cm,text=black,line cap=round,line join=round,font='+FONT+',',
        r'every node/.style={outer sep=0pt,inner sep=0pt,align=center}]']
def finish(lines):return '\n'.join(lines+[r'\end{tikzpicture}',r'\endgroup',''])
def count_chart(topic):
    lines=start('Source: docs/literature_stats/yearly.json.');a=lines.append
    x0,x1,h=.85,10.95,2.75
    years=sorted(map(int,topic['counts']));values=[topic['counts'][str(y)] for y in years]
    has_partial=2026 in years
    ts=ticks(max(values));scale=h/ts[-1];pitch=(x1-x0)/len(years);bw=pitch*.62
    a(r'\path[use as bounding box] (0,-0.72) rectangle (11.2,3.28);')
    a(r'\node[anchor=west,font='+SMALL+r'] at (0.10,3.05) {论文数量（篇）};')
    if has_partial:
        a(r'\node[anchor=east,font='+SMALL+r'] at (10.95,3.05) {*2026年截至10月29日};')
    for t in ts:
        y=t*scale
        if t:a(fr'\draw[litLine!22,line width=.35pt] ({x0},{y:.3f}) -- ({x1},{y:.3f});')
        a(fr'\node[anchor=east] at ({x0-.14},{y:.3f}) {{{t}}};')
    a(fr'\draw[litDark,line width=.7pt] ({x0},{h}) -- ({x0},0) -- ({x1},0);')
    for i,(year,value) in enumerate(zip(years,values)):
        x=x0+(i+.5)*pitch;y=value*scale
        bar_style='litDark,fill=white,line width=.65pt' if year==2026 else 'litDark,fill=litLine,line width=.4pt'
        a(fr'\draw[{bar_style}] ({x-bw/2:.3f},0) rectangle ({x+bw/2:.3f},{y:.3f});')
        a(fr'\node[anchor=south,font={SMALL}] at ({x:.3f},{y+.06:.3f}) {{{value}}};')
        year_label=str(year)+('*' if year==2026 else '')
        a(fr'\node[anchor=north,font={SMALL}] at ({x:.3f},-.13) {{{year_label}}};')
    a(fr'\node[anchor=east,font={SMALL}] at ({x1},-.58) {{发表年份}};')
    return finish(lines)
def year_x(year, topic, axis):
    """A monotone piecewise-linear calendar map; the recent years get more room."""
    start=topic['start_year']
    if year <= 2022:
        return axis['early_left_cm']+(year-start)/(2022-start)*(axis['early_right_cm']-axis['early_left_cm'])
    if year <= axis['recent_start']:
        return axis['early_right_cm']+(year-2022)*(axis['recent_left_cm']-axis['early_right_cm'])
    return axis['recent_left_cm']+(year-axis['recent_start'])*axis['recent_step_cm']

def validate_nodes(spec):
    """Guard against a diagram year drifting from its referenced formal version."""
    import re
    bibliography=(FIGURES.parent/'references.bib').read_text()
    entries={}
    for item in re.split(r'(?m)^@',bibliography)[1:]:
        key=re.match(r'[^\{]+\{([^,]+),',item)
        year=re.search(r'\byear\s*=\s*\{(\d{4})\}',item)
        if key and year:entries[key[1]]=int(year[1])
    for topic in spec['topics'].values():
        for route in topic['routes']:
            for node in route['nodes']:
                if entries.get(node['key'])!=node['year']:
                    raise ValueError('Timeline year does not match bibliography: '+str(node))

def route_diagram(topic, axis):
    lines=start('Nodes: docs/literature_stats/timeline_nodes.json; non-uniform calendar axis.');a=lines.append
    n=len(topic['routes']);lane_step=1.42 if n==4 else 1.48;first=-1.04
    last=first-(n-1)*lane_step
    has_preprint=any(node.get('preprint') for route in topic['routes'] for node in route['nodes'])
    bottom=last-(1.10 if has_preprint else .96)
    # Native width is 14.45 cm, without a document-width resizebox.
    a(fr'\path[use as bounding box] (0,{bottom:.3f}) rectangle (14.45,.40);')
    # Alternate light-blue bands behind the lanes, as in a survey-style timeline.
    band_h=lane_step-.08
    for i in range(n):
        if i%2==0:
            y=first-i*lane_step
            a(fr'\path[fill=litTint] (0.05,{y-band_h/2:.3f}) rectangle (13.95,{y+band_h/2:.3f});')
    a(fr'\draw[litDark,line width=.7pt,-{{Stealth[length=1.4mm,width=1.0mm]}}] ({axis["early_left_cm"]},0) -- ({axis["right_cm"]+.30},0);')
    ticks=topic['early_ticks']+list(range(2023,2027))
    for year in ticks:
        x=year_x(year,topic,axis)
        a(fr'\draw[litDark,line width=.55pt] ({x:.3f},-.05) -- ({x:.3f},.05);')
        a(fr'\node[anchor=south,font={SMALL}] at ({x:.3f},.08) {{{year}}};')
        a(fr'\draw[litLine!18,line width=.35pt] ({x:.3f},-.17) -- ({x:.3f},{last-.88:.3f});')
    # Two small slashes signal the scale change without removing any dates.
    split=(axis['early_right_cm']+axis['recent_left_cm'])/2
    a(fr'\draw[white,line width=3pt] ({split-.12:.3f},0) -- ({split+.12:.3f},0);')
    for shift in (-.045,.045):
        xx=split+shift
        a(fr'\draw[litDark,line width=.6pt] ({xx-.055:.3f},-.08) -- ({xx+.055:.3f},.08);')
    for i,route in enumerate(topic['routes']):
        y=first-i*lane_step
        lab_fill='litTint' if i%2==0 else 'white'
        # The tinted band is the row itself; no lane line is drawn through it.
        label=route.get('display_name',esc(route['name']))
        a(fr'\node[font={HEAD},text width=2.08cm] at (1.08,{y:.3f}) {{{label}}};')
        for node in route['nodes']:
            x=year_x(node['year'],topic,axis)
            preprint=node.get('preprint',False)
            a(fr'\node[draw=litDark,fill={"white" if preprint else "litDark"},circle,line width=.55pt,minimum size=3.2pt,inner sep=0pt] at ({x:.3f},{y:.3f}) {{}};')
            up=node.get('side','up')=='up'
            sign=1 if up else -1
            anchor='south' if up else 'north'
            name=node['name'] if '$' in node['name'] else esc(node['name'])
            if preprint:name+=r'$^{\dagger}$'
            # The label keeps only the method name; its role is explained in the text.
            lx=x+node.get('label_dx',0)
            ly=y+sign*.12
            if abs(lx-x)>.015:
                a(fr'\draw[litLine!60,line width=.35pt] ({x:.3f},{y+sign*.07:.3f}) -- ({lx:.3f},{ly:.3f});')
            a(fr'\node[anchor={anchor},font={SMALL},fill={lab_fill},inner sep=1pt] at ({lx:.3f},{ly:.3f}) {{{name}}};')
    if has_preprint:
        a(fr'\node[anchor=west,font={SMALL}] at (.10,{bottom+.20:.3f}) {{空心节点及 $\dagger$ 表示预印本。}};')
    return finish(lines)
WRAPPER=r'''\documentclass[border=1mm]{standalone}
\usepackage[UTF8,fontset=fandol]{ctex}
\usepackage{tikz}
\usetikzlibrary{arrows.meta}
\IfFontExistsTF{Times New Roman}{\setmainfont{Times New Roman}}{}
\IfFontExistsTF{Songti SC}{\setCJKmainfont{Songti SC}[AutoFakeBold=2]}{}
\IfFontExistsTF{Heiti SC}{\setCJKfamilyfont{zhhei}{Heiti SC}[AutoFakeBold=2]}{}
\begin{document}
\input{%s}
\end{document}
'''
def export(name):
    for tool in ('xelatex','pdftoppm'):
        if not shutil.which(tool):raise RuntimeError('Missing '+tool)
    WORK.mkdir(parents=True,exist_ok=True);OUT.mkdir(parents=True,exist_ok=True)
    wrapper=WORK/(name+'.tex');wrapper.write_text(WRAPPER%(FIGURES/(name+'.tex')))
    p=subprocess.run(['xelatex','-interaction=nonstopmode','-halt-on-error',wrapper.name],cwd=WORK,capture_output=True,text=True)
    if p.returncode:raise RuntimeError(name+'\n'+p.stdout[-3000:])
    shutil.copy2(WORK/(name+'.pdf'),OUT/(name+'.pdf'))
    for suffix,extra in (('',[]),('-gray',['-gray'])):
        subprocess.run(['pdftoppm','-png','-r','180','-singlefile',*extra,str(OUT/(name+'.pdf')),str(OUT/(name+suffix))],check=True,capture_output=True)
    print('Exported',name,flush=True)
def main():
    timeline_only='--timelines-only' in sys.argv
    spec=json.loads((STATS/'timeline_nodes.json').read_text())
    validate_nodes(spec)
    jobs=[]
    if not timeline_only:
        stats=json.loads((STATS/'yearly.json').read_text())
        macro_names={'T1':'Reconstruction','T2':'WorldModel','T3':'Action'};macros=[]
        for topic in stats['topics']:
            tid=topic['id'];stem=spec['topics'][tid]['stem']
            jobs.append(('literature_counts_'+stem,count_chart(topic)))
            for label,y in (('Start',2015),('Recent',2021),('End',2025)):
                macros.append(r'\def\lit'+macro_names[tid]+label+'{'+str(topic['counts'][str(y)])+'}')
            if '2026' in topic['counts']:
                macros.append(r'\def\lit'+macro_names[tid]+'Partial{'+str(topic['counts']['2026'])+'}')
        OUT.mkdir(parents=True,exist_ok=True)
        (OUT/'stat_values.tex').write_text('\n'.join(macros)+'\n')
    for topic in spec['topics'].values():
        jobs.append(('literature_timeline_'+topic['stem'],route_diagram(topic,spec['axis'])))
    for name,source in jobs:
        (FIGURES/(name+'.tex')).write_text(source)
        if '--tex' not in sys.argv:export(name)
    # A timeline-only preview must not overwrite the statistical provenance receipt.
    if not timeline_only:
        manifest=dict(data_sha256=hashlib.sha256((STATS/'yearly.json').read_bytes()).hexdigest(),nodes_sha256=hashlib.sha256((STATS/'timeline_nodes.json').read_bytes()).hexdigest(),natural_dimensions_cm=dict(counts=[11.2,4.0],timelines_width=14.45),timeline_axis=spec['axis'],figures=[name for name,_ in jobs])
        (OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2))
if __name__=='__main__':main()
